def _decorate() -> None:
    for lang, msgs in MESSAGES.items():
        for key, emoji in EMOJI_PREFIX.items():
            if key in msgs and not msgs[key].startswith(emoji):
                msgs[key] = f"{emoji} {msgs[key]}"
        for key in THANKS_SUFFIX:
            if key in msgs:
                msgs[key] = f"{msgs[key]} {_MERCI[lang]} {THANKS}"


_decorate()


def t(lang: str | None, key: str, **kw) -> str:
    lang = lang if lang in MESSAGES else "fr"
    text = MESSAGES[lang].get(key) or MESSAGES["fr"][key]
    return text.format(**kw) if kw else text


def plural(lang: str | None, n: int, key: str) -> str:
    """« 1 champ lu », « 109 champs lus » : accord sans « (s) »."""
    one, many = t(lang, key).split("|")
    word = one if n == 1 else many
    return word.format(n=n) if "{n}" in word else f"{n} {word}"
